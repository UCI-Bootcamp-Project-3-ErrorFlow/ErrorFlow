require('dotenv').config();
const express = require('express');
const { join } = require('path');
const http = require('http');
const socketio = require('socket.io');
const passport = require('passport');
const helmet = require('helmet');
const rateLimit = require('express-rate-limit');
const { Strategy } = require('passport-local');
const { Strategy: JWTStrategy, ExtractJwt } = require('passport-jwt');

if (!process.env.SECRET) {
  console.error('SECRET env var is required to sign and verify JWTs');
  process.exit(1);
}

const app = express();
const { User } = require('./models');
const { addUser, removeUser, getUser, getUsersInRoom } = require('./users.js');
const server = http.createServer(app);
const io = socketio(server);

app.disable('x-powered-by');
app.use(helmet({ contentSecurityPolicy: false }));
app.use('/api', rateLimit({ windowMs: 15 * 60 * 1000, max: 300 }));
app.use('/api/users', rateLimit({ windowMs: 15 * 60 * 1000, max: 30 }));

// app.use('/uploads', express.static('uploads'));
app.use(express.static(join(__dirname, 'client', 'build')));
app.use(express.urlencoded({ extended: true, limit: '100kb' }));
app.use(express.json({ limit: '100kb' }));
// authentication
app.use(passport.initialize());

passport.use(new Strategy(User.authenticate()));
passport.serializeUser(User.serializeUser());
passport.deserializeUser(User.deserializeUser());
passport.use(
  new JWTStrategy(
    {
      jwtFromRequest: ExtractJwt.fromAuthHeaderAsBearerToken(),
      secretOrKey: process.env.SECRET,
    },
    ({ id }, cb) =>
      User.findById(id)
        .populate('posts')
        .then((user) => cb(null, user))
        .catch((err) => cb(err))
  )
);

app.use(require('./routes'));
app.get('*', (req, res) => {
  res.sendFile(join(__dirname, 'client', 'build', 'index.html'));
});

io.on('connect', (socket) => {
  socket.on('join', ({ name, room }, callback) => {
    if (typeof name !== 'string' || typeof room !== 'string' || !name.trim() || !room.trim()) {
      return callback('Name and room are required');
    }
    const { error, user } = addUser({
      id: socket.id,
      name,
      room,
    });
    //error=username is already registered
    if (error) return callback(error);
    socket.join(user.room);
    // event generatd by admin to user
    socket.emit('message', {
      user: 'admin',
      text: `Hello ${user.name}, welcome to ${user.room}`,
    });

    socket.broadcast.to(user.room).emit('message', {
      user: 'admin',
      text: `${user.name} has joined!`,
    });
    // socket.join(user, room);

    socket.to(user.room).emit('roomData', {
      room: user.room,
      users: getUsersInRoom(user.room),
    });
    //after emit has been executed(passing data) from Chat.js, this callback is going to return whatever in the callback to the Chat.js
    callback();

    //event generated by user to everyone
    socket.on('sendMessage', (message, callback) => {
      const user = getUser(socket.id);
      if (!user || typeof message !== 'string' || message.length > 2000) {
        return callback();
      }
      io.to(user.room).emit('message', {
        user: user.name,
        text: message,
      });
      callback();
    });
    // On when disconnect
    socket.on('disconnect', () => {
      const user = removeUser(socket.id);
      if (user) {
        io.to(user.room).emit('message', {
          user: 'admin',
          text: `${user.name} has left the room.`,
        });
        io.to(user.room).emit('roomData', {
          room: user.room,
          users: getUsersInRoom(user.room),
        });
      }
    });
  });
});

require('mongoose')
  .connect(process.env.DB_URI || process.env.LOCAL_URI)
  .then(() => server.listen(process.env.PORT || 3001))
  .catch((err) => console.error(err));
